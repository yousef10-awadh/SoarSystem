class Command(BaseCommand):
    help = 'Adds or updates 15 Arabic security awareness courses and their quizzes.'

    def handle(self, *args, **options):
        media_root = Path(settings.MEDIA_ROOT).resolve()
        media_root.mkdir(parents=True, exist_ok=True)
        added = updated = question_count = 0

        for course_index, data in enumerate(COURSES, start=1):
            slug = f'course-{course_index:02d}'
            relative_path = f'courses/{slug}/index.html'
            course_dir = (media_root / 'courses' / slug).resolve()
            if media_root not in course_dir.parents:
                raise ValueError('Generated course path escaped MEDIA_ROOT.')
            course_dir.mkdir(parents=True, exist_ok=True)
            (course_dir / 'index.html').write_text(render_course_page(data), encoding='utf-8')

            course = Course.objects.filter(title=data['title']).order_by('id').first()
            if course is None:
                course = Course.objects.create(
                    title=data['title'], description=data['description'],
                    estimated_minutes=data['minutes'], passing_score=80,
                    launch_path=relative_path, is_active=True,
                )
                added += 1
            else:
                course.description = data['description']
                course.estimated_minutes = data['minutes']
                course.passing_score = 80
                course.launch_path = relative_path
                course.is_active = True
                course.save(update_fields=['description', 'estimated_minutes', 'passing_score', 'launch_path', 'is_active'])
                updated += 1

            course.questions.all().delete()
            for index, question_data in enumerate(data['questions'], start=1):
                prompt, option_a, option_b, option_c, option_d, correct_option = question_data
                values = {
                    'prompt': prompt, 'option_a': option_a, 'option_b': option_b,
                    'option_c': option_c, 'option_d': option_d,
                    'correct_option': correct_option, 'order': index,
                }
                CourseQuestion.objects.create(course=course, **values)
                question_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'تم تجهيز {len(COURSES)} دورة: أُضيفت {added}، حُدثت {updated}، '
            f'وجُهز {question_count} سؤالًا. محتوى الدورات محفوظ داخل MEDIA_ROOT.'
        ))
